#!/usr/bin/env python3
"""One metadata source -> classic JS for file:// and an interoperable JSON manifest.

Python standard library only. Run after adding a WebP and editing data/stickers.json.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = {"greeting", "happy", "confused", "comfort", "sleepy", "daily", "playful", "shy", "love"}
REQUIRED = {"id", "title", "filename", "category", "mood", "keywords", "description", "story", "is_featured", "version"}


def load_catalog(root: Path = ROOT) -> list[dict]:
    items = json.loads((root / "data/stickers.json").read_text(encoding="utf-8"))
    if not isinstance(items, list) or not items:
        raise ValueError("Catalog must be a nonempty JSON list")
    ids, paths = set(), set()
    for item in items:
        if not isinstance(item, dict) or set(item) != REQUIRED:
            raise ValueError("Every sticker must have exactly the documented metadata fields")
        if not isinstance(item["id"], str) or not re.fullmatch(r"[a-z]+(?:-[a-z0-9]+)+", item["id"]):
            raise ValueError("Sticker IDs must be portable lowercase slugs")
        if item["category"] not in CATEGORIES:
            raise ValueError(f"Unknown category: {item['category']}")
        expected = f"assets/stickers/{item['category']}/{item['id']}.webp"
        if item["filename"] != expected or item["id"] in ids or expected in paths:
            raise ValueError("Duplicate ID/path or noncanonical filename")
        for field in ("title", "description", "story"):
            if not isinstance(item[field], str) or not item[field].strip():
                raise ValueError(f"{field} must be nonempty text")
        for field in ("mood", "keywords"):
            if not isinstance(item[field], list) or not item[field] or any(not isinstance(x, str) or not x.strip() for x in item[field]):
                raise ValueError(f"{field} must be a nonempty text list")
        if type(item["is_featured"]) is not bool or type(item["version"]) is not int or item["version"] < 1:
            raise ValueError("Invalid feature flag or version")
        path = root / expected
        if any(p.is_symlink() for p in (path, *path.parents) if p.is_relative_to(root)):
            raise ValueError("Asset paths must not be symlinks")
        if not path.resolve(strict=True).is_relative_to(root.resolve()):
            raise ValueError("Asset escaped repository root")
        ids.add(item["id"])
        paths.add(expected)
    return items


def outputs(root: Path = ROOT) -> dict[Path, str]:
    items = load_catalog(root)
    encoded = json.dumps(items, ensure_ascii=False, indent=2)
    manifest = {
        "schema_version": 1, "collection": "Tuanban · 团斑", "character": "tuanban", "version": "1.0.0",
        "license": "MPL-2.0", "notice": "ASSET-NOTICE.md",
        "format": {"width": 1024, "height": 1024, "mime": "image/webp", "alpha": False},
        "stickers": [item | {"width": 1024, "height": 1024, "bytes": (root / item["filename"]).stat().st_size,
                             "sha256": hashlib.sha256((root / item["filename"]).read_bytes()).hexdigest()}
                     for item in items]
    }
    return {root / "data/stickers.js": "// Generated by scripts/build_manifest.py; edit stickers.json instead.\nwindow.TUANBAN_STICKERS = " + encoded + ";\n",
            root / "data/manifest.json": json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"}


def build(root: Path = ROOT, check: bool = False) -> None:
    for path, text in outputs(root).items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                raise ValueError(f"Stale generated metadata: {path.name}; run build_manifest.py")
        else:
            path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without editing")
    args = parser.parse_args()
    build(check=args.check)
    print("Manifest and offline JS are current." if args.check else "Generated manifest and offline JS.")
